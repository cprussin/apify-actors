const raw = (name: string) =>
  readFileSync(new URL(`./fixtures/${name}`, import.meta.url), "utf8");
const json = (name: string): unknown => JSON.parse(raw(name));

const PLAYER = json("player-android.json");
const MICRO = json("player-web-microformat.json");
const UNAVAILABLE = json("player-unavailable.json");
const TT_EN = raw("timedtext-en.xml");
const TT_ASR = raw("timedtext-asr.xml");
const BOT = {
  playabilityStatus: {
    status: "LOGIN_REQUIRED",
    reason: "Sign in to confirm you’re not a bot",
  },
};
const NO_CAPTIONS = { ...(PLAYER as object), captions: undefined };

interface Call {
  url: string;
  init: HttpInit;
  session: string;
  body: Record<string, unknown>;
}

type Reply = { status?: number; body: unknown; location?: string };
type Handler = (c: Call) => Reply | undefined;

/** Fake YouTube: routes requests to fixtures; `override` wins when it returns a reply. */
function fakeYouTube(override?: Handler) {
  const calls: Call[] = [];
  const fetch: FetchFn = async (url, init, session) => {
    const body = init.body ? JSON.parse(init.body) : {};
    const call = { url, init, session, body };
    calls.push(call);
    const r: Reply = override?.(call) ?? route(call);
    const text = typeof r.body === "string" ? r.body : JSON.stringify(r.body);
    return {
      status: r.status ?? 200,
      headers: { get: (h) => (h === "location" ? (r.location ?? null) : null) },
      text: async () => text,
    };
  };
  const route = (c: Call): Reply => {
    const client = (c.body.context as { client: { clientName: string } })
      ?.client?.clientName;
    if (c.url.includes("/player")) {
      if (client === "WEB") return { body: MICRO };
      if (c.body.videoId === "aaaaaaaaaaa") return { body: UNAVAILABLE };
      if (c.body.videoId === "nocaptions1") return { body: NO_CAPTIONS };
      return { body: PLAYER };
    }
    if (c.url.includes("/api/timedtext"))
      return { body: c.url.includes("kind=asr") ? TT_ASR : TT_EN };
    if (c.url.includes("/navigation/resolve_url"))
      return { body: json("resolve-url.json") };
    if (c.url.includes("/browse"))
      return {
        body: c.body.continuation
          ? json("browse-continuation.json")
          : json("browse-playlist.json"),
      };
    return { status: 404, body: "not found" };
  };
  const client = () =>
    new YouTubeClient({ fetch, backoffMs: 0, sleep: async () => {} });
  return { fetch, calls, client };
}

const OPTS = {
  languages: ["en"],
  allowAutoGenerated: true,
  fallbackToAnyLanguage: true,
  formats: ["text", "segments"] as ("text" | "segments" | "srt" | "vtt")[],
  includeMetadata: true,
};

describe("sources", () => {
  it("parses video URLs and IDs", () => {
    for (const u of [
      "dQw4w9WgXcQ",
      "https://www.youtube.com/watch?v=dQw4w9WgXcQ&t=10s",
      "youtube.com/watch?v=dQw4w9WgXcQ",
      "https://youtu.be/dQw4w9WgXcQ?si=abc",
      "https://m.youtube.com/watch?v=dQw4w9WgXcQ",
      "https://www.youtube.com/shorts/dQw4w9WgXcQ",
      "https://www.youtube.com/embed/dQw4w9WgXcQ",
      "https://www.youtube.com/live/dQw4w9WgXcQ",
      "https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ",
      "https://music.youtube.com/watch?v=dQw4w9WgXcQ&list=RDxyz",
    ]) {
      expect(parseSource(u)).toMatchObject({
        kind: "video",
        videoId: "dQw4w9WgXcQ",
      });
    }
  });

  it("parses playlists and channels", () => {
    expect(
      parseSource(
        "https://www.youtube.com/playlist?list=PLOGi5-fAu8bH_T9HhH9V2B5izEE4G5waV",
      ),
    ).toMatchObject({
      kind: "playlist",
      playlistId: "PLOGi5-fAu8bH_T9HhH9V2B5izEE4G5waV",
    });
    expect(parseSource("https://www.youtube.com/@TED/videos")).toMatchObject({
      kind: "channel",
      url: "https://www.youtube.com/@TED",
      tab: "videos",
    });
    expect(parseSource("@mkbhd")).toMatchObject({
      kind: "channel",
      tab: "all",
    });
    expect(
      parseSource(
        "https://www.youtube.com/channel/UCuAXFkgsw1L7xaCfnd5JJOw/shorts",
      ),
    ).toMatchObject({
      kind: "channel",
      channelId: "UCuAXFkgsw1L7xaCfnd5JJOw",
      tab: "shorts",
    });
    expect(parseSource("https://www.youtube.com/c/Foo")).toMatchObject({
      kind: "channel",
      url: "https://www.youtube.com/c/Foo",
    });
    expect(uploadsPlaylistId("UCuAXFkgsw1L7xaCfnd5JJOw", "all")).toBe(
      "UUuAXFkgsw1L7xaCfnd5JJOw",
    );
    expect(uploadsPlaylistId("UCuAXFkgsw1L7xaCfnd5JJOw", "videos")).toBe(
      "UULFuAXFkgsw1L7xaCfnd5JJOw",
    );
  });

  it("rejects non-YouTube input", () => {
    expect(() => parseSource("https://vimeo.com/123")).toThrow();
    expect(() => parseSource("hello world")).toThrow();
    expect(() => parseSource("https://www.youtube.com/watch?x=1")).toThrow();
  });
});

