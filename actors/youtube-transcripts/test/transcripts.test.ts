describe("client", () => {
  it("retries blocks with a fresh session, then gives up", async () => {
    let n = 0;
    const yt = fakeYouTube((c) =>
      c.url.includes("/player") && n++ < 2
        ? {
            status: 302,
            body: "",
            location: "https://www.google.com/sorry/index",
          }
        : undefined,
    );
    const client = yt.client();
    const p = parsePlayer(await client.player("dQw4w9WgXcQ", "ANDROID"));
    expect(p.playability).toBe("ok");
    const sessions = new Set(yt.calls.map((c) => c.session));
    expect(sessions.size).toBe(3);
    expect(client.stats.blocks).toBe(2);
    expect(yt.calls[0]!.init.headers!["X-Goog-FieldMask"]).toContain(
      "captions",
    );

    const always = fakeYouTube(() => ({ status: 429, body: "Too many" }));
    await expect(
      always.client().timedText("https://www.youtube.com/api/timedtext?v=x"),
    ).rejects.toBeInstanceOf(BlockedError);
    expect(always.calls).toHaveLength(4);
  });
});

describe("fetchTranscript", () => {
  it("returns transcript, segments and metadata", async () => {
    const yt = fakeYouTube();
    const item = await fetchTranscript(yt.client(), "dQw4w9WgXcQ", "src", {
      ...OPTS,
      formats: ["text", "segments", "srt", "vtt"],
    });
    expect(item).toMatchObject({
      videoId: "dQw4w9WgXcQ",
      url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
      title:
        "Rick Astley - Never Gonna Give You Up (Official Video) (4K Remaster)",
      channelName: "Rick Astley",
      channelId: "UCuAXFkgsw1L7xaCfnd5JJOw",
      publishDate: "2009-10-24T23:57:33-07:00",
      durationSec: 213,
      language: "en",
      isAutoGenerated: false,
      isTranslated: false,
      error: null,
    });
    expect(item.transcript).toMatch(/^\[♪♪♪\] ♪ We're no strangers to love ♪/);
    expect(item.wordCount).toBeGreaterThan(300);
    expect(item.segments!.length).toBe(parseTimedText(TT_EN).length);
    expect(item.srt).toMatch(/^1\n00:00:01,360 --> /);
    expect(item.vtt).toMatch(/^WEBVTT/);
    expect(item.availableLanguages).toContainEqual({
      code: "en",
      name: "English (auto-generated)",
      isAutoGenerated: true,
    });
    const tt = yt.calls.find((c) => c.url.includes("timedtext"))!;
    expect(tt.url).not.toContain("fmt=");
  });

  it("uses auto-generated when manual is excluded, and translates", async () => {
    const yt = fakeYouTube();
    const client = yt.client();
    const auto = await fetchTranscript(client, "dQw4w9WgXcQ", "s", {
      ...OPTS,
      languages: ["en", "fr"],
      formats: ["text"],
      includeMetadata: false,
    });
    expect(auto.language).toBe("en");
    expect(auto.segments).toBeUndefined();
    expect(auto.channelName).toBeUndefined();
    const tr = await fetchTranscript(client, "dQw4w9WgXcQ", "s", {
      ...OPTS,
      translateTo: "fr",
      includeMetadata: false,
    });
    expect(tr).toMatchObject({
      language: "fr",
      languageName: "French",
      isTranslated: true,
    });
    expect(yt.calls.at(-1)!.url).toContain("tlang=fr");
    // A track already in the target language is used as-is.
    const pt = await fetchTranscript(client, "dQw4w9WgXcQ", "s", {
      ...OPTS,
      translateTo: "pt",
      includeMetadata: false,
    });
    expect(pt).toMatchObject({ language: "pt-BR", isTranslated: false });
  });

  it("returns error items for expected failures", async () => {
    const yt = fakeYouTube();
    const client = yt.client();
    const missing = await fetchTranscript(client, "aaaaaaaaaaa", "s", OPTS);
    expect(missing).toMatchObject({
      errorCode: "videoUnavailable",
      transcript: null,
    });
    const none = await fetchTranscript(client, "nocaptions1", "s", OPTS);
    expect(none).toMatchObject({
      errorCode: "noCaptions",
      title: expect.any(String),
    });
    const lang = await fetchTranscript(client, "dQw4w9WgXcQ", "s", {
      ...OPTS,
      languages: ["ko"],
      fallbackToAnyLanguage: false,
    });
    expect(lang.errorCode).toBe("languageNotAvailable");
    expect(lang.error).toContain("de-DE");
  });

  it("cycles clients on bot checks and throws when all fail", async () => {
    let bots = 2;
    const yt = fakeYouTube((c) =>
      c.url.includes("/player") && bots-- > 0 ? { body: BOT } : undefined,
    );
    const item = await fetchTranscript(yt.client(), "dQw4w9WgXcQ", "s", OPTS);
    expect(item.error).toBeNull();
    const clients = yt.calls
      .filter((c) => c.url.includes("/player"))
      .map(
        (c) =>
          (c.body.context as { client: { clientName: string } }).client
            .clientName,
      );
    expect(clients.slice(0, 3)).toEqual(["ANDROID", "ANDROID_VR", "IOS"]);

    const always = fakeYouTube((c) =>
      c.url.includes("/player") ? { body: BOT } : undefined,
    );
    await expect(
      fetchTranscript(always.client(), "dQw4w9WgXcQ", "s", OPTS),
    ).rejects.toBeInstanceOf(BlockedError);
  });
});

describe("runTranscripts", () => {
  it("expands sources, dedupes, charges only successes, stops at budget", async () => {
    const yt = fakeYouTube((c) =>
      c.url.includes("/player") && c.body.videoId === "UF8uR6Z6KLc"
        ? { body: BOT }
        : undefined,
    );
    const items: [TranscriptItem, boolean][] = [];
    const stats = await runTranscripts(
      normalizeInput({
        urls: [
          "dQw4w9WgXcQ",
          "aaaaaaaaaaa",
          "UF8uR6Z6KLc",
          "https://www.youtube.com/channel/UCuAXFkgsw1L7xaCfnd5JJOw",
          "https://www.youtube.com/@missing",
        ],
        maxVideosPerSource: 3,
        maxConcurrency: 2,
      }),
      {
        newClient: yt.client,
        emit: async (item, charge) => (items.push([item, charge]), true),
      },
    );
    expect(stats).toMatchObject({
      videos: 6,
      succeeded: 4,
      failed: 2,
      failures: { videoUnavailable: 1, blocked: 1 },
      stopReason: "done",
    });
    expect(stats.sourceErrors).toHaveLength(0);
    expect(items.filter(([, c]) => c)).toHaveLength(4);
    expect(items.filter(([i, c]) => c !== (i.error === null))).toHaveLength(0);

    let charged = 0;
    const budget = await runTranscripts(
      normalizeInput({
        urls: ["https://www.youtube.com/channel/UCuAXFkgsw1L7xaCfnd5JJOw"],
        maxVideosPerSource: 50,
      }),
      {
        newClient: yt.client,
        emit: async (_i, c) => (c ? ++charged < 3 : true),
      },
    );
    expect(budget.stopReason).toBe("budget");
    expect(charged).toBe(3);
  });

  it("onlyNew: skips videos returned before, retries failures", async () => {
    const CHANNEL = "https://www.youtube.com/channel/UCuAXFkgsw1L7xaCfnd5JJOw";
    const go = async (urls: string[], state: unknown, failId?: string) => {
      const yt = fakeYouTube((c) =>
        c.url.includes("/player") && c.body.videoId === failId
          ? { body: BOT }
          : undefined,
      );
      const seen = new Seen(state);
      const items: [TranscriptItem, boolean][] = [];
      const stats = await runTranscripts(
        normalizeInput({ urls, maxVideosPerSource: 3, onlyNew: true }),
        {
          newClient: yt.client,
          seen,
          emit: async (item, charge) => (items.push([item, charge]), true),
        },
      );
      const ok = items.filter(([, c]) => c).map(([i]) => i.videoId);
      return { ok, stats, state: seen.toJSON() };
    };
    const r1 = await go([CHANNEL, "UF8uR6Z6KLc"], undefined, "UF8uR6Z6KLc");
    expect(r1.ok).toHaveLength(3);
    // The 3 channel videos are known: the streak stops the channel; the
    // failed video is retried.
    const r2 = await go([CHANNEL, "UF8uR6Z6KLc"], r1.state);
    expect(r2.ok).toEqual(["UF8uR6Z6KLc"]);
    expect(r2.stats.skippedSeen).toBe(ONLY_NEW_SEEN_STREAK);
    const r3 = await go([CHANNEL, "UF8uR6Z6KLc"], r2.state);
    expect(r3.ok).toEqual([]);
    expect(r3.stats).toMatchObject({ videos: 0, sourceErrors: [] });
  });

  it("records source errors", async () => {
    const yt = fakeYouTube((c) =>
      c.url.includes("resolve_url") ? { body: { endpoint: {} } } : undefined,
    );
    const stats = await runTranscripts(normalizeInput({ urls: ["@nobody"] }), {
      newClient: yt.client,
      emit: async () => true,
    });
    expect(stats.videos).toBe(0);
    expect(stats.sourceErrors[0]).toContain("Channel not found");
  });
});
