describe("captions", () => {
  it("decodes double-escaped entities and strips tags", () => {
    expect(cleanCaptionText("We&amp;#39;re no\nstrangers")).toBe(
      "We're no strangers",
    );
    expect(
      cleanCaptionText(
        "&lt;font color=&quot;#E5E5E5&quot;&gt;hi&lt;/font&gt; &amp;amp; bye",
      ),
    ).toBe("hi & bye");
  });

  it("parses manual and auto-generated timedtext", () => {
    const en = parseTimedText(TT_EN);
    expect(en.length).toBeGreaterThan(40);
    expect(en[1]).toEqual({
      start: 18.64,
      duration: 3.24,
      text: "♪ We're no strangers to love ♪",
    });
    const asr = parseTimedText(TT_ASR);
    expect(asr[1]!.text).toBe("We're no strangers to");
    expect(segmentsToText(asr)).toMatch(
      /^\[Music\] We're no strangers to love/,
    );
    expect(parseTimedText("<transcript></transcript>")).toEqual([]);
  });

  it("renders SRT and VTT with non-overlapping cues", () => {
    const segs = [
      { start: 0.32, duration: 14.26, text: "[Music]" },
      { start: 18.8, duration: 7.16, text: "We're no strangers to" },
      { start: 21.8, duration: 7.319, text: "love." },
    ];
    expect(toSrt(segs)).toBe(
      "1\n00:00:00,320 --> 00:00:14,580\n[Music]\n\n" +
        "2\n00:00:18,800 --> 00:00:21,800\nWe're no strangers to\n\n" +
        "3\n00:00:21,800 --> 00:00:29,119\nlove.\n",
    );
    expect(toVtt(segs)).toMatch(
      /^WEBVTT\n\n00:00:00\.320 --> 00:00:14\.580\n\[Music\]\n/,
    );
    expect(formatTimestamp(3723.5, ",")).toBe("01:02:03,500");
  });
});

describe("player", () => {
  it("parses tracks and metadata", () => {
    const p = parsePlayer(PLAYER);
    expect(p.playability).toBe("ok");
    expect(p.tracks.map((t) => t.languageCode)).toEqual([
      "en",
      "en",
      "de-DE",
      "ja",
      "pt-BR",
      "es-419",
    ]);
    expect(p.tracks[1]!.isAutoGenerated).toBe(true);
    expect(p.details).toMatchObject({
      title:
        "Rick Astley - Never Gonna Give You Up (Official Video) (4K Remaster)",
      channelName: "Rick Astley",
      channelId: "UCuAXFkgsw1L7xaCfnd5JJOw",
      durationSec: 213,
    });
    expect(p.details.viewCount).toBeGreaterThan(1e9);
    expect(p.translationLanguages.length).toBeGreaterThan(5);
    expect(parseMicroformat(MICRO)).toMatchObject({
      publishDate: "2009-10-24T23:57:33-07:00",
      category: "Music",
    });
  });

  it("classifies playability", () => {
    expect(parsePlayer(UNAVAILABLE).playability).toBe("unavailable");
    expect(parsePlayer(BOT).playability).toBe("botCheck");
    expect(
      parsePlayer({
        playabilityStatus: {
          status: "LOGIN_REQUIRED",
          reason: "This video is private",
        },
      }).playability,
    ).toBe("private");
    expect(
      parsePlayer({
        playabilityStatus: {
          status: "LOGIN_REQUIRED",
          reason: "Sign in to confirm your age",
        },
      }).playability,
    ).toBe("loginRequired");
  });

  it("selects tracks by preference", () => {
    const t = (languageCode: string, auto = false): CaptionTrack => ({
      languageCode,
      languageName: languageCode,
      isAutoGenerated: auto,
      isTranslatable: true,
      baseUrl: `https://www.youtube.com/api/timedtext?lang=${languageCode}&fmt=srv3`,
    });
    const tracks = [t("en", true), t("de-DE"), t("pt-BR"), t("fr", true)];
    const prefs = { allowAutoGenerated: true, fallbackToAnyLanguage: true };
    expect(selectTrack(tracks, { ...prefs, languages: ["de"] })).toBe(
      tracks[1],
    );
    expect(selectTrack(tracks, { ...prefs, languages: ["pt-BR"] })).toBe(
      tracks[2],
    );
    expect(selectTrack(tracks, { ...prefs, languages: ["en"] })).toBe(
      tracks[0],
    );
    expect(
      selectTrack(tracks, {
        ...prefs,
        languages: ["en"],
        allowAutoGenerated: false,
      }),
    ).toBe(tracks[1]);
    expect(selectTrack(tracks, { ...prefs, languages: ["ja"] })).toBe(
      tracks[1],
    );
    expect(
      selectTrack(tracks, {
        ...prefs,
        languages: ["ja"],
        fallbackToAnyLanguage: false,
      }),
    ).toBeUndefined();
    const url = new URL(timedTextUrl(tracks[0]!, "es"));
    expect(url.searchParams.get("fmt")).toBeNull();
    expect(url.searchParams.get("tlang")).toBe("es");
  });
});

